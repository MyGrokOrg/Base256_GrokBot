/* Generates include/base256/detail/tables.hpp with MPFR:
 *   - log reduction tables (two stages) for detail_dd::log
 *   - erf/erfc expansion centers c_j = j/16: erfc(c_j) and (2/sqrt(pi)) e^{-c_j^2}
 * Every value is stored as a double-float256 (hi, lo), hi = RN237(v), lo = RN237(v - hi),
 * encoded as four little-endian uint64 words per float256.
 * Build: cc -O2 tools/gen_tables.c -lmpfr -lgmp -o gen && ./gen > include/base256/detail/tables.hpp */
#include <mpfr.h>
#include <stdint.h>
#include <stdio.h>

#define PREC 2000
static void enc(mpfr_t v, uint64_t w[4]) { /* v already rounded to 237 bits, normal or zero */
    w[0] = w[1] = w[2] = w[3] = 0;
    if (mpfr_zero_p(v)) return;
    int neg = mpfr_signbit(v);
    mpfr_exp_t e;
    mpfr_t m; mpfr_init2(m, 237); mpfr_abs(m, v, MPFR_RNDN);
    e = mpfr_get_exp(m) - 1; /* value = 1.f * 2^e */
    mpz_t z; mpz_init(z);
    mpfr_set_exp(m, 237); /* m in [2^236, 2^237) */
    mpfr_get_z(z, m, MPFR_RNDN);
    mpz_clrbit(z, 236);
    for (int i = 0; i < 4; ++i) { w[i] = mpz_getlimbn(z, i); }
    if (sizeof(mp_limb_t) != 8) { fprintf(stderr, "need 64-bit limbs\n"); }
    uint64_t be = (uint64_t)(e + 262143);
    w[3] |= be << 44;
    if (neg) w[3] |= 1ULL << 63;
    mpz_clear(z); mpfr_clear(m);
}
static void emit_dd(mpfr_t v) {
    mpfr_t hi, lo, t; mpfr_inits2(237, hi, lo, (mpfr_ptr)0); mpfr_init2(t, PREC);
    mpfr_set(hi, v, MPFR_RNDN); mpfr_sub(t, v, hi, MPFR_RNDN); mpfr_set(lo, t, MPFR_RNDN);
    uint64_t a[4], b[4]; enc(hi, a); enc(lo, b);
    printf("{%#llx,%#llx,%#llx,%#llx,%#llx,%#llx,%#llx,%#llx}",
           (unsigned long long)a[0], (unsigned long long)a[1], (unsigned long long)a[2], (unsigned long long)a[3],
           (unsigned long long)b[0], (unsigned long long)b[1], (unsigned long long)b[2], (unsigned long long)b[3]);
    mpfr_clears(hi, lo, t, (mpfr_ptr)0);
}
/* inverse of c rounded to `bits` significant bits (exact as a double) */
static double short_inv(mpfr_t c, int bits) {
    mpfr_t r; mpfr_init2(r, bits); mpfr_ui_div(r, 1, c, MPFR_RNDN);
    double d = mpfr_get_d(r, MPFR_RNDN); mpfr_clear(r); return d;
}
int main(void) {
    mpfr_t c, v, inv;
    mpfr_inits2(PREC, c, v, inv, (mpfr_ptr)0);
    printf("#pragma once\n// Generated by tools/gen_tables.c (MPFR, %d bits). Do not edit.\n", PREC);
    printf("#include <cstdint>\n\nnamespace base256::detail_dd::tables {\n\n");
    /* log stage 1: c_j = 1 + j/128, j in [-32, 63]; inv1 has 20 bits; table holds -log(inv1). */
    printf("inline constexpr int kLog1Lo = -32, kLog1Hi = 63;\n");
    printf("inline constexpr double kLog1Inv[96] = {");
    for (int j = -32; j <= 63; ++j) { mpfr_set_si(c, 128 + j, MPFR_RNDN); mpfr_div_ui(c, c, 128, MPFR_RNDN);
        printf("%s%a", j == -32 ? "" : ",", j == 0 ? 1.0 : short_inv(c, 20)); }
    printf("};\ninline constexpr std::uint64_t kLog1Val[96][8] = {\n");
    for (int j = -32; j <= 63; ++j) { mpfr_set_si(c, 128 + j, MPFR_RNDN); mpfr_div_ui(c, c, 128, MPFR_RNDN);
        double d = j == 0 ? 1.0 : short_inv(c, 20); mpfr_set_d(inv, d, MPFR_RNDN); mpfr_log(v, inv, MPFR_RNDN); mpfr_neg(v, v, MPFR_RNDN);
        emit_dd(v); printf(",\n"); }
    printf("};\n");
    /* log stage 2: c_k = 1 + k/2^15, k in [-192, 192]; inv2 has 40 bits. */
    printf("inline constexpr int kLog2Lo = -192, kLog2Hi = 192;\n");
    printf("inline constexpr double kLog2Inv[385] = {");
    for (int k = -192; k <= 192; ++k) { mpfr_set_si(c, 32768 + k, MPFR_RNDN); mpfr_div_ui(c, c, 32768, MPFR_RNDN);
        printf("%s%a", k == -192 ? "" : ",", k == 0 ? 1.0 : short_inv(c, 40)); }
    printf("};\ninline constexpr std::uint64_t kLog2Val[385][8] = {\n");
    for (int k = -192; k <= 192; ++k) { mpfr_set_si(c, 32768 + k, MPFR_RNDN); mpfr_div_ui(c, c, 32768, MPFR_RNDN);
        double d = k == 0 ? 1.0 : short_inv(c, 40); mpfr_set_d(inv, d, MPFR_RNDN); mpfr_log(v, inv, MPFR_RNDN); mpfr_neg(v, v, MPFR_RNDN);
        emit_dd(v); printf(",\n"); }
    printf("};\n");
    /* erf/erfc centers c_j = j/16, j = 0..256: erfc(c_j) and (2/sqrt(pi)) e^{-c_j^2} */
    printf("inline constexpr int kErfCenters = 257;  // c_j = j/16\n");
    printf("inline constexpr std::uint64_t kErfcVal[257][8] = {\n");
    for (int j = 0; j <= 256; ++j) { mpfr_set_ui(c, j, MPFR_RNDN); mpfr_div_ui(c, c, 16, MPFR_RNDN); mpfr_erfc(v, c, MPFR_RNDN); emit_dd(v); printf(",\n"); }
    printf("};\n// (2/sqrt(pi)) exp(-c_j^2)\ninline constexpr std::uint64_t kErfK[257][8] = {\n");
    for (int j = 0; j <= 256; ++j) { mpfr_set_ui(c, j, MPFR_RNDN); mpfr_div_ui(c, c, 16, MPFR_RNDN);
        mpfr_sqr(v, c, MPFR_RNDN); mpfr_neg(v, v, MPFR_RNDN); mpfr_exp(v, v, MPFR_RNDN);
        mpfr_const_pi(inv, MPFR_RNDN); mpfr_sqrt(inv, inv, MPFR_RNDN); mpfr_div(v, v, inv, MPFR_RNDN); mpfr_mul_ui(v, v, 2, MPFR_RNDN);
        emit_dd(v); printf(",\n"); }
    printf("};\n\n} // namespace base256::detail_dd::tables\n");
    mpfr_clears(c, v, inv, (mpfr_ptr)0);
    return 0;
}
