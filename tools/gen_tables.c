/* Generates include/base256/detail/tables.hpp with MPFR:
 *   - log reduction tables (two stages) for detail_dd::log
 *   - atan(j/64) for detail_math::atan_dd, sin/cos(j/64) for sincos_reduced
 *   - erf/erfc expansion centers c_j = j/16: erfc(c_j) and (2/sqrt(pi)) e^{-c_j^2}
 * Every value is stored as a double-float256 (hi, lo), hi = RN237(v), lo = RN237(v - hi),
 * encoded as four little-endian uint64 words per float256.
 * Build: cc -O2 tools/gen_tables.c -lmpfr -lgmp -o gen && ./gen > include/base256/detail/tables.hpp */
#include <mpfr.h>
#include <stdint.h>
#include <stdio.h>

#define PREC 2000
static void enc(mpfr_t v, uint64_t w[4]) { /* v already rounded to 237 bits, normal or zero */
    w[0] = w[1] = w[2] = w[3] = 0;
    if (mpfr_zero_p(v)) return;
    int neg = mpfr_signbit(v);
    mpfr_exp_t e;
    mpfr_t m; mpfr_init2(m, 237); mpfr_abs(m, v, MPFR_RNDN);
    e = mpfr_get_exp(m) - 1; /* value = 1.f * 2^e */
    mpz_t z; mpz_init(z);
    mpfr_set_exp(m, 237); /* m in [2^236, 2^237) */
    mpfr_get_z(z, m, MPFR_RNDN);
    mpz_clrbit(z, 236);
    for (int i = 0; i < 4; ++i) { w[i] = mpz_getlimbn(z, i); }
    if (sizeof(mp_limb_t) != 8) { fprintf(stderr, "need 64-bit limbs\n"); }
    uint64_t be = (uint64_t)(e + 262143);
    w[3] |= be << 44;
    if (neg) w[3] |= 1ULL << 63;
    mpz_clear(z); mpfr_clear(m);
}
static void emit_dd(mpfr_t v) {
    mpfr_t hi, lo, t; mpfr_inits2(237, hi, lo, (mpfr_ptr)0); mpfr_init2(t, PREC);
    mpfr_set(hi, v, MPFR_RNDN); mpfr_sub(t, v, hi, MPFR_RNDN); mpfr_set(lo, t, MPFR_RNDN);
    uint64_t a[4], b[4]; enc(hi, a); enc(lo, b);
    printf("{%#llx,%#llx,%#llx,%#llx,%#llx,%#llx,%#llx,%#llx}",
           (unsigned long long)a[0], (unsigned long long)a[1], (unsigned long long)a[2], (unsigned long long)a[3],
           (unsigned long long)b[0], (unsigned long long)b[1], (unsigned long long)b[2], (unsigned long long)b[3]);
    mpfr_clears(hi, lo, t, (mpfr_ptr)0);
}
/* inverse of c rounded to `bits` significant bits (exact as a double) */
static double short_inv(mpfr_t c, int bits) {
    mpfr_t r; mpfr_init2(r, bits); mpfr_ui_div(r, 1, c, MPFR_RNDN);
    double d = mpfr_get_d(r, MPFR_RNDN); mpfr_clear(r); return d;
}
int main(void) {
    mpfr_t c, v, inv;
    mpfr_inits2(PREC, c, v, inv, (mpfr_ptr)0);
    printf("#pragma once\n// Generated by tools/gen_tables.c (MPFR, %d bits). Do not edit.\n", PREC);
    printf("#include <cstdint>\n\nnamespace base256::detail_dd::tables {\n\n");
    /* log stage 1: c_j = 1 + j/128, j in [-32, 63]; inv1 has 20 bits; table holds -log(inv1). */
    printf("inline constexpr int kLog1Lo = -32, kLog1Hi = 63;\n");
    printf("inline constexpr double kLog1Inv[96] = {");
    for (int j = -32; j <= 63; ++j) { mpfr_set_si(c, 128 + j, MPFR_RNDN); mpfr_div_ui(c, c, 128, MPFR_RNDN);
        printf("%s%a", j == -32 ? "" : ",", j == 0 ? 1.0 : short_inv(c, 20)); }
    printf("};\ninline constexpr std::uint64_t kLog1Val[96][8] = {\n");
    for (int j = -32; j <= 63; ++j) { mpfr_set_si(c, 128 + j, MPFR_RNDN); mpfr_div_ui(c, c, 128, MPFR_RNDN);
        double d = j == 0 ? 1.0 : short_inv(c, 20); mpfr_set_d(inv, d, MPFR_RNDN); mpfr_log(v, inv, MPFR_RNDN); mpfr_neg(v, v, MPFR_RNDN);
        emit_dd(v); printf(",\n"); }
    printf("};\n");
    /* log stage 2: c_k = 1 + k/2^15, k in [-192, 192]; inv2 has 40 bits. */
    printf("inline constexpr int kLog2Lo = -192, kLog2Hi = 192;\n");
    printf("inline constexpr double kLog2Inv[385] = {");
    for (int k = -192; k <= 192; ++k) { mpfr_set_si(c, 32768 + k, MPFR_RNDN); mpfr_div_ui(c, c, 32768, MPFR_RNDN);
        printf("%s%a", k == -192 ? "" : ",", k == 0 ? 1.0 : short_inv(c, 40)); }
    printf("};\ninline constexpr std::uint64_t kLog2Val[385][8] = {\n");
    for (int k = -192; k <= 192; ++k) { mpfr_set_si(c, 32768 + k, MPFR_RNDN); mpfr_div_ui(c, c, 32768, MPFR_RNDN);
        double d = k == 0 ? 1.0 : short_inv(c, 40); mpfr_set_d(inv, d, MPFR_RNDN); mpfr_log(v, inv, MPFR_RNDN); mpfr_neg(v, v, MPFR_RNDN);
        emit_dd(v); printf(",\n"); }
    printf("};\n");
    /* erf/erfc centers c_j = j/16, j = 0..256: erfc(c_j) and (2/sqrt(pi)) e^{-c_j^2} */
    printf("inline constexpr int kErfCenters = 257;  // c_j = j/16\n");
    printf("inline constexpr std::uint64_t kErfcVal[257][8] = {\n");
    for (int j = 0; j <= 256; ++j) { mpfr_set_ui(c, j, MPFR_RNDN); mpfr_div_ui(c, c, 16, MPFR_RNDN); mpfr_erfc(v, c, MPFR_RNDN); emit_dd(v); printf(",\n"); }
    printf("};\n// (2/sqrt(pi)) exp(-c_j^2)\ninline constexpr std::uint64_t kErfK[257][8] = {\n");
    for (int j = 0; j <= 256; ++j) { mpfr_set_ui(c, j, MPFR_RNDN); mpfr_div_ui(c, c, 16, MPFR_RNDN);
        mpfr_sqr(v, c, MPFR_RNDN); mpfr_neg(v, v, MPFR_RNDN); mpfr_exp(v, v, MPFR_RNDN);
        mpfr_const_pi(inv, MPFR_RNDN); mpfr_sqrt(inv, inv, MPFR_RNDN); mpfr_div(v, v, inv, MPFR_RNDN); mpfr_mul_ui(v, v, 2, MPFR_RNDN);
        emit_dd(v); printf(",\n"); }
    printf("};\n");
    /* atan(j/64), j = 0..64 */
    printf("inline constexpr std::uint64_t kAtanVal[65][8] = {\n");
    for (int j = 0; j <= 64; ++j) { mpfr_set_ui(c, j, MPFR_RNDN); mpfr_div_ui(c, c, 64, MPFR_RNDN); mpfr_atan(v, c, MPFR_RNDN); emit_dd(v); printf(",\n"); }
    printf("};\n");
    /* sin(j/64), cos(j/64), j = 0..64 */
    printf("inline constexpr std::uint64_t kSinVal[65][8] = {\n");
    for (int j = 0; j <= 64; ++j) { mpfr_set_ui(c, j, MPFR_RNDN); mpfr_div_ui(c, c, 64, MPFR_RNDN); mpfr_sin(v, c, MPFR_RNDN); emit_dd(v); printf(",\n"); }
    printf("};\ninline constexpr std::uint64_t kCosVal[65][8] = {\n");
    for (int j = 0; j <= 64; ++j) { mpfr_set_ui(c, j, MPFR_RNDN); mpfr_div_ui(c, c, 64, MPFR_RNDN); mpfr_cos(v, c, MPFR_RNDN); emit_dd(v); printf(",\n"); }
    printf("};\n");
    /* Stirling: c_k = B_2k / (2k (2k-1)), B_2k = (-1)^(k+1) 2 (2k)! zeta(2k) / (2 pi)^(2k), k = 1..140 */
    printf("inline constexpr int kStirlingN = 140;\ninline constexpr std::uint64_t kStirling[140][8] = {\n");
    {
        mpfr_t f, z, tp; mpfr_inits2(PREC, f, z, tp, (mpfr_ptr)0);
        mpfr_const_pi(tp, MPFR_RNDN); mpfr_mul_ui(tp, tp, 2, MPFR_RNDN);
        for (int k = 1; k <= 140; ++k) {
            mpfr_fac_ui(f, 2 * k, MPFR_RNDN); mpfr_zeta_ui(z, 2 * k, MPFR_RNDN);
            mpfr_mul(v, f, z, MPFR_RNDN); mpfr_mul_ui(v, v, 2, MPFR_RNDN);
            mpfr_pow_ui(c, tp, 2 * k, MPFR_RNDN); mpfr_div(v, v, c, MPFR_RNDN);
            if (k % 2 == 0) mpfr_neg(v, v, MPFR_RNDN);
            mpfr_div_ui(v, v, 2 * k * (2 * k - 1), MPFR_RNDN);
            emit_dd(v); printf(",\n");
        }
        mpfr_clears(f, z, tp, (mpfr_ptr)0);
    }
    printf("};\n");
    /* Euler's gamma and c3 = gamma^3/6 - gamma pi^2/12 + zeta(3)/3 (1/Gamma(1+z) = 1 + gamma z + c2 z^2 + c3 z^3 + ...) */
    {
        mpfr_t g, t, u; mpfr_inits2(PREC, g, t, u, (mpfr_ptr)0);
        mpfr_const_euler(g, MPFR_RNDN);
        printf("inline constexpr std::uint64_t kEulerGamma[8] = "); emit_dd(g); printf(";\n");
        mpfr_pow_ui(v, g, 3, MPFR_RNDN); mpfr_div_ui(v, v, 6, MPFR_RNDN);
        mpfr_const_pi(t, MPFR_RNDN); mpfr_sqr(t, t, MPFR_RNDN); mpfr_mul(t, t, g, MPFR_RNDN); mpfr_div_ui(t, t, 12, MPFR_RNDN);
        mpfr_sub(v, v, t, MPFR_RNDN);
        mpfr_zeta_ui(u, 3, MPFR_RNDN); mpfr_div_ui(u, u, 3, MPFR_RNDN); mpfr_add(v, v, u, MPFR_RNDN);
        printf("inline constexpr std::uint64_t kInvGammaC3[8] = "); emit_dd(v); printf(";\n");
        mpfr_clears(g, t, u, (mpfr_ptr)0);
    }
    /* 1/Gamma(1+x) = sum_k a_k x^k, k = 0..111: exp of -lnGamma(1+x) = gamma x - sum_{k>=2} (-1)^k zeta(k)/k x^k
       via n f_n = sum_{k=1..n} k g_k f_{n-k}. |a_k| 2^-k < 2^-490 for k >= 108. */
    {
        enum { NR = 112 };
        mpfr_t g[NR], f[NR], t; mpfr_init2(t, PREC);
        for (int k = 0; k < NR; ++k) { mpfr_init2(g[k], PREC); mpfr_init2(f[k], PREC); }
        mpfr_set_ui(g[0], 0, MPFR_RNDN); mpfr_const_euler(g[1], MPFR_RNDN);
        for (int k = 2; k < NR; ++k) { mpfr_zeta_ui(g[k], k, MPFR_RNDN); mpfr_div_ui(g[k], g[k], k, MPFR_RNDN); if (k % 2 == 0) mpfr_neg(g[k], g[k], MPFR_RNDN); }
        mpfr_set_ui(f[0], 1, MPFR_RNDN);
        for (int n = 1; n < NR; ++n) {
            mpfr_set_ui(f[n], 0, MPFR_RNDN);
            for (int k = 1; k <= n; ++k) { mpfr_mul(t, g[k], f[n - k], MPFR_RNDN); mpfr_mul_ui(t, t, k, MPFR_RNDN); mpfr_add(f[n], f[n], t, MPFR_RNDN); }
            mpfr_div_ui(f[n], f[n], n, MPFR_RNDN);
        }
        printf("inline constexpr int kRGamma1pN = %d;\ninline constexpr std::uint64_t kRGamma1p[%d][8] = {\n", NR, NR);
        for (int k = 0; k < NR; ++k) { emit_dd(f[k]); printf(",\n"); }
        printf("};\n");
        for (int k = 0; k < NR; ++k) { mpfr_clear(g[k]); mpfr_clear(f[k]); }
        mpfr_clear(t);
    }
    /* B_2k/(2k)! = (-1)^(k+1) 2 zeta(2k) / (2 pi)^(2k), k = 1..140 (Euler-Maclaurin) */
    {
        mpfr_t z, tp; mpfr_inits2(PREC, z, tp, (mpfr_ptr)0);
        mpfr_const_pi(tp, MPFR_RNDN); mpfr_mul_ui(tp, tp, 2, MPFR_RNDN);
        printf("inline constexpr int kBernFactN = 140;\ninline constexpr std::uint64_t kBernFact[140][8] = {\n");
        for (int k = 1; k <= 140; ++k) {
            mpfr_zeta_ui(z, 2 * k, MPFR_RNDN); mpfr_mul_ui(v, z, 2, MPFR_RNDN);
            mpfr_pow_ui(c, tp, 2 * k, MPFR_RNDN); mpfr_div(v, v, c, MPFR_RNDN);
            if (k % 2 == 0) mpfr_neg(v, v, MPFR_RNDN);
            emit_dd(v); printf(",\n");
        }
        printf("};\n");
        /* ln p for the primes p < 64 (zeta's direct sum) */
        printf("inline constexpr std::uint64_t kLnPrime64[18][8] = {\n");
        for (int n = 2; n < 64; ++n) {
            int pr = 1; for (int d = 2; d * d <= n; ++d) if (n % d == 0) pr = 0;
            if (!pr) continue;
            mpfr_set_ui(v, n, MPFR_RNDN); mpfr_log(v, v, MPFR_RNDN); emit_dd(v); printf(",\n");
        }
        printf("};\n");
        mpfr_clears(z, tp, (mpfr_ptr)0);
    }
    printf("\n} // namespace base256::detail_dd::tables\n");
    mpfr_clears(c, v, inv, (mpfr_ptr)0);
    return 0;
}
